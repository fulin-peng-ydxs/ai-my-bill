import { beforeEach, describe, expect, it, vi } from 'vitest'
const state = vi.hoisted(() => ({ dataset: 'original', exportCsv: vi.fn(), save: vi.fn(), discard: vi.fn() }))
vi.mock('../data/management/dataManagement', () => ({ dataManagement: { exportCsv: state.exportCsv } }))
vi.mock('../data/appDatabase', () => ({ appDatabase: { read: async () => [{ dataset_id: state.dataset }] } }))
vi.mock('../platform/ledgerTransfers', () => ({ ledgerTransfers: { saveTransfer: state.save,discardTransfer: state.discard } }))
beforeEach(() => {
  vi.resetModules()
  vi.resetAllMocks()
  state.dataset = 'original'
  state.exportCsv.mockResolvedValue({ id: 'capability',rows: 2 })
  state.save.mockResolvedValue({ saved: true })
  state.discard.mockResolvedValue(undefined)
})
describe('本地导出任务与原生文件边界', () => {
  it('同范围幂等复用，完成才打开原生保存，取消保存仍回收临时文件', async () => {
    const api = await import('./exports')
    await api.createExport({ scope: 'ALL_DATA' },'one')
    await api.createExport({ scope: 'ALL_DATA' },'one')
    expect(state.exportCsv).toHaveBeenCalledOnce()
    await expect(api.createExport({ scope: 'CURRENT_FILTERS',query: '',type: 'INCOME',lifecycle: 'ACTIVE',range: 'TODAY' },'one')).rejects.toMatchObject({ code: 'IDEMPOTENCY_CONFLICT' })
    const job = await api.getExport('one')
    expect(job).toMatchObject({ status: 'SUCCEEDED',rowCount: 2,downloadUrl: 'native-export:capability' })
    state.save.mockResolvedValueOnce({ saved: false })
    expect(await api.downloadExport(job.downloadUrl!,'账单.csv')).toBe(false)
    expect(state.save).toHaveBeenCalledWith({ id: 'capability',filename: '账单.csv' })
    expect(state.discard).toHaveBeenCalledOnce()
    await expect(api.getExport('one')).rejects.toMatchObject({ code: 'EXPORT_EXPIRED' })
  })
  it('数据集切换使旧完成结果过期，不打开旧文件选择器', async () => {
    const api = await import('./exports')
    await api.createExport({ scope: 'ALL_DATA' },'old')
    state.dataset = 'restored'
    expect((await api.getExport('old')).status).toBe('EXPIRED')
    expect(state.discard).toHaveBeenCalledWith({ id: 'capability' })
    expect(state.save).not.toHaveBeenCalled()
  })
  it('慢导出取消等待终态，迟到文件也只回收一次', async () => {
    let finish!: (value: { id: string; rows: number }) => void
    state.exportCsv.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    const api = await import('./exports')
    await api.createExport({ scope: 'ALL_DATA' },'slow')
    const cancel = api.cancelExport('slow')
    expect(state.exportCsv.mock.calls[0][1].aborted).toBe(true)
    finish({ id: 'late',rows: 4 })
    expect((await cancel).status).toBe('CANCELLED')
    expect(state.discard).toHaveBeenCalledExactlyOnceWith({ id: 'late' })
    expect(state.save).not.toHaveBeenCalled()
  })
  it('失败、空结果及原生保存失败不留下可重复下载任务', async () => {
    const api = await import('./exports')
    state.exportCsv.mockRejectedValueOnce(new Error('controlled-export'))
    await api.createExport({ scope: 'ALL_DATA' },'failed')
    expect((await api.getExport('failed')).status).toBe('FAILED')
    state.exportCsv.mockResolvedValueOnce({ id: 'empty',rows: 0 })
    await api.createExport({ scope: 'ALL_DATA' },'empty')
    expect((await api.getExport('empty')).rowCount).toBe(0)
    await expect(api.getExport('empty')).rejects.toMatchObject({ code: 'EXPORT_EXPIRED' })
    await api.createExport({ scope: 'ALL_DATA' },'save-failed')
    const job = await api.getExport('save-failed')
    state.save.mockRejectedValueOnce(new Error('controlled-picker'))
    await expect(api.downloadExport(job.downloadUrl!,'账单.csv')).rejects.toThrow('controlled-picker')
    await expect(api.getExport('save-failed')).rejects.toMatchObject({ code: 'EXPORT_EXPIRED' })
  })
  it('保存和临时清理同时失败保留两项原因，旧任务不再提供下载', async () => {
    const api = await import('./exports')
    await api.createExport({ scope: 'ALL_DATA' },'both-failed')
    const job = await api.getExport('both-failed')
    const save = new Error('controlled-save'),cleanup = new Error('controlled-cleanup')
    state.save.mockRejectedValueOnce(save)
    state.discard.mockRejectedValueOnce(cleanup)
    await expect(api.downloadExport(job.downloadUrl!,'账单.csv')).rejects.toMatchObject({ errors: [save,cleanup] })
    await expect(api.getExport('both-failed')).rejects.toMatchObject({ code: 'EXPORT_EXPIRED' })
  })

})
